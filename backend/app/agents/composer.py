"""Composer Specialist Role (Section 5.2 & Phase 6).

Responsible for chord progressions, basslines, melody motifs, key/scale
consistency, humanization, and deterministic MIDI validation.
"""

from __future__ import annotations

import os
from dataclasses import dataclass, field
from typing import Dict, List, Optional

from ..music_engine import (
    GenrePresetRegistry,
    MidiPattern,
    ScaleType,
    ValidationResult,
    apply_humanization,
    export_midi_file,
    generate_bassline,
    generate_chord_pattern,
    generate_melody,
    validate_midi_notes,
)


@dataclass
class CompositionBundle:
    """Complete harmonic and melodic bundle generated by ComposerAgent."""
    genre_key: str
    root: str
    scale: str
    tempo_bpm: float
    bars: int
    chords: MidiPattern
    bassline: MidiPattern
    melody: MidiPattern
    validations: Dict[str, ValidationResult] = field(default_factory=dict)
    exported_midi_files: Dict[str, str] = field(default_factory=dict)
    stylistic_disclaimer: str = (
        "Generated MIDI patterns satisfy key, scale, and meter constraints as editable "
        "starting points; stylistic perfection is not objectively guaranteed."
    )

    @property
    def is_valid(self) -> bool:
        return all(v.is_valid for v in self.validations.values())


class ComposerAgent:
    """Specialist logical module for harmonic and melodic composition."""

    def __init__(self, preset_registry: Optional[GenrePresetRegistry] = None):
        self.presets = preset_registry or GenrePresetRegistry()

    def compose(
        self,
        *,
        genre: str = "melodic_techno",
        root: Optional[str] = None,
        scale: Optional[str] = None,
        tempo_bpm: Optional[float] = None,
        bars: int = 4,
        humanize: bool = True,
        export_dir: Optional[str] = None,
    ) -> CompositionBundle:
        """Produce chords, bassline, and melody adhering strictly to key/scale and bar length."""
        preset = self.presets.get(genre)
        eff_root = root or (preset.default_root if preset else "A")
        eff_scale_str = scale or (preset.default_scale if preset else "natural_minor")
        eff_tempo = tempo_bpm or (preset.default_bpm if preset else 124.0)
        progression = preset.chord_progression if preset else ["i", "VI", "III", "VII"]
        bass_rhythm = preset.bass_rhythm if preset else "pumping"
        density = preset.melody_density if preset else 0.5
        vel_var = preset.velocity_variation if preset else 0.05
        swing = preset.swing_amount if preset else 0.01

        try:
            scale_enum = ScaleType(eff_scale_str.lower())
        except ValueError:
            scale_enum = ScaleType.NATURAL_MINOR

        bars_per_chord = max(0.25, float(bars) / len(progression))

        # 1. Generate raw patterns
        chords = generate_chord_pattern(
            root=eff_root,
            scale=scale_enum.value,
            progression=progression,
            bars_per_chord=bars_per_chord,
            tempo=eff_tempo,
        )
        bassline = generate_bassline(
            root=eff_root,
            scale=scale_enum.value,
            progression=progression,
            bars_per_chord=bars_per_chord,
            tempo=eff_tempo,
            rhythm=bass_rhythm,
        )
        melody = generate_melody(
            root=eff_root,
            scale=scale_enum.value,
            progression=progression,
            bars=bars,
            density=density,
            tempo=eff_tempo,
        )

        # 2. Optional velocity & timing humanization
        if humanize:
            chords = apply_humanization(chords, velocity_variation=vel_var * 0.5, swing_amount=0.0)
            bassline = apply_humanization(bassline, velocity_variation=vel_var, swing_amount=swing)
            melody = apply_humanization(melody, velocity_variation=vel_var, swing_amount=swing)

        # 3. Deterministic MIDI validation
        validations = {
            "chords": validate_midi_notes(chords.notes, max_bars=float(bars), expected_root=eff_root, expected_scale=scale_enum),
            "bassline": validate_midi_notes(bassline.notes, max_bars=float(bars), expected_root=eff_root, expected_scale=scale_enum),
            "melody": validate_midi_notes(melody.notes, max_bars=float(bars), expected_root=eff_root, expected_scale=scale_enum),
        }

        exported: Dict[str, str] = {}
        if export_dir:
            os.makedirs(export_dir, exist_ok=True)
            exported["chords"] = export_midi_file(chords, os.path.join(export_dir, f"{genre}_chords.mid"))
            exported["bassline"] = export_midi_file(bassline, os.path.join(export_dir, f"{genre}_bassline.mid"))
            exported["melody"] = export_midi_file(melody, os.path.join(export_dir, f"{genre}_melody.mid"))

        return CompositionBundle(
            genre_key=genre,
            root=eff_root,
            scale=scale_enum.value,
            tempo_bpm=eff_tempo,
            bars=bars,
            chords=chords,
            bassline=bassline,
            melody=melody,
            validations=validations,
            exported_midi_files=exported,
            stylistic_disclaimer=preset.stylistic_disclaimer if preset else CompositionBundle.stylistic_disclaimer,
        )
